import Foundation

/// Сколько детей можно завести.
///
/// Бесплатно — один, с Pro сколько угодно. Это ограничение **ёмкости**, а не
/// доступа к уже введённым данным, поэтому оно не нарушает правило «не паволим
/// собственные записи пользователя».
///
/// Отсюда главное следствие: **лимит ограничивает ДОБАВЛЕНИЕ, а не доступ.**
/// Если человек купил Pro, завёл троих, а потом покупка отвалилась (возврат,
/// чужое устройство, сбой) — все трое остаются на месте и переключаются как
/// прежде. Прятать или удалять уже введённые дневники нельзя ни при каких
/// обстоятельствах: это была бы потеря данных за деньги.
enum ChildLimit {

    /// Сколько детей доступно без Pro.
    static let freeLimit = 1

    static func canAdd(currentCount: Int, isPro: Bool) -> Bool {
        isPro || currentCount < freeLimit
    }
}
